// Matches 병무청's full 복무기관 list against the institution registry and
// writes the nationwide census:
//   docs/sources/mma-roster/census.csv     one row per 복무기관
//   docs/INSTITUTION_ROSTER_CENSUS.md      summary tables
//
//   node scripts/fetch-mma-service-institutions.cjs   (needs a data.go.kr key)
//   node scripts/institution-roster-census.cjs
//
// Matching uses the registry's own name normalisation, so a row counts as
// covered only where the app's lookup would find the same record.
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const rosterDir = path.join(root, "docs/sources/mma-roster");
const roster = JSON.parse(
  fs.readFileSync(path.join(rosterDir, "roster.json"), "utf8"),
);
const meta = JSON.parse(
  fs.readFileSync(path.join(rosterDir, "meta.json"), "utf8"),
);
const registry = JSON.parse(
  fs.readFileSync(
    path.join(root, "packages/rules/institutions/registry.json"),
    "utf8",
  ),
);
const scopeRules = JSON.parse(
  fs.readFileSync(path.join(rosterDir, "scope-rules.json"), "utf8"),
).rules.map((rule) => ({ ...rule, regex: new RegExp(rule.pattern) }));
const jejuResearch = JSON.parse(
  fs.readFileSync(path.join(rosterDir, "jeju-research.json"), "utf8"),
).parents;

// Same as normalizeInstitutionName in packages/rules/src/institutions.ts.
const normalize = (name) =>
  name
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\s\p{P}\p{S}]+/gu, "");
const withoutParenthetical = (name) => name.replace(/\(.*?\)/g, "").trim();

const byKey = new Map();
for (const institution of registry.institutions) {
  for (const name of [institution.name, ...institution.aliases]) {
    byKey.set(normalize(name), institution);
  }
}
const lookup = (name) =>
  name
    ? (byKey.get(normalize(name)) ??
      byKey.get(normalize(withoutParenthetical(name))))
    : undefined;
const scope = (name) =>
  name ? scopeRules.find((rule) => rule.regex.test(name)) : undefined;

const STATUS = {
  OWN: "기관 자체 기록",
  PARENT: "대표기관 기록",
  SCOPE: "상위 규정 적용범위",
  NONE: "병무청 공통 규정",
};

function classify(row) {
  const own = lookup(row.bokmuGgm);
  if (own) return { status: "OWN", registryId: own.id };
  const parent = lookup(row.dpBokmuGgm);
  if (parent) return { status: "PARENT", registryId: parent.id };
  const rule = scope(row.bokmuGgm) ?? scope(row.dpBokmuGgm);
  if (rule) return { status: "SCOPE", registryId: rule.registryId };
  return { status: "NONE", registryId: "" };
}

const rows = roster.map((row) => ({ ...row, ...classify(row) }));
const csvCell = (value) => {
  const text = value ?? "";
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
};
const columns = [
  ["bmgigwanCd", "기관코드"],
  ["bokmuGgm", "복무기관"],
  ["dpBokmuGgm", "대표기관"],
  ["ssggdaeBr", "분류"],
  ["gtcdNm", "관할청"],
  ["bjdsggjusoCd", "시군구코드"],
  ["status", "판정"],
  ["registryId", "레지스트리ID"],
];
fs.writeFileSync(
  path.join(rosterDir, "census.csv"),
  [
    columns.map(([, label]) => label).join(","),
    ...rows.map((row) =>
      columns.map(([key]) => csvCell(String(row[key] ?? ""))).join(","),
    ),
  ].join("\n") + "\n",
);

const count = (list) => {
  const counts = { OWN: 0, PARENT: 0, SCOPE: 0, NONE: 0 };
  for (const row of list) counts[row.status] += 1;
  return counts;
};
const pct = (part, whole) =>
  whole ? `${((100 * part) / whole).toFixed(1)}%` : "0%";
const tableRow = (label, list) => {
  const c = count(list);
  const covered = c.OWN + c.PARENT + c.SCOPE;
  return `| ${label} | ${list.length} | ${c.OWN} | ${c.PARENT} | ${c.SCOPE} | ${c.NONE} | ${pct(covered, list.length)} |`;
};
const groupBy = (list, key) => {
  const groups = new Map();
  for (const row of list) {
    const value = row[key] ?? "(없음)";
    if (!groups.has(value)) groups.set(value, []);
    groups.get(value).push(row);
  }
  return [...groups.entries()].sort((a, b) => b[1].length - a[1].length);
};
const header =
  "| 구분 | 복무기관 | 자체 기록 | 대표기관 기록 | 상위 규정 | 병무청 공통 규정 | 기관별 근거 비율 |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: |";

const parents = groupBy(rows, "dpBokmuGgm");
const parentsWithRecord = parents.filter(([name]) => lookup(name)).length;
const uncoveredParents = parents
  .filter(([, list]) => list.every((row) => row.status === "NONE"))
  .slice(0, 60);
const jeju = rows.filter((row) => row.gtcdNm === "제주");
const jejuParents = groupBy(jeju, "dpBokmuGgm");

const lines = [
  "# Institution Roster Census (병무청 복무기관 전수 대조)",
  "",
  "<!-- GENERATED by scripts/institution-roster-census.cjs. Do not edit; rerun the script. -->",
  "",
  `병무청 「사회복무요원 복무기관」 open API (data.go.kr 3066757), fetched ${meta.fetchedAt.slice(0, 10)}: **${roster.length}** 복무기관 under **${parents.length}** 대표기관. ` +
    "Each 복무기관 is matched against `packages/rules/institutions/registry.json` with the same name normalisation the app's lookup uses. " +
    "The full per-institution result is `docs/sources/mma-roster/census.csv`.",
  "",
  "판정 (in this order):",
  "",
  `- **${STATUS.OWN}** (OWN): the 복무기관's own name is a registry record or alias.`,
  `- **${STATUS.PARENT}** (PARENT): its 대표기관 (병무청's 대표복무기관, e.g. the 구청 for a 사회복지시설) is a registry record. The record's scopeNote says whom its rules cover; check it before applying.`,
  `- **${STATUS.SCOPE}** (SCOPE): a branch office covered by a registry record's rule through that rule's own scope clause (\`docs/sources/mma-roster/scope-rules.json\`).`,
  `- **${STATUS.NONE}** (NONE): no public institution-level evidence was found, so the app applies the nationwide 병무청 rules (\`commonServiceRules\` in \`packages/rules/src/common-service-rules.ts\`: 1일 중식비 최소 9,000원, 교통비는 대중교통 왕복요금 기준, 휴가·결근일 미지급). An institution with different rules is corrected through user reports.`,
  "",
  "## Nationwide",
  "",
  header,
  tableRow("**전체**", rows),
  ...groupBy(rows, "ssggdaeBr").map(([name, list]) => tableRow(name, list)),
  "",
  `대표기관 with their own registry record: **${parentsWithRecord}** of ${parents.length}.`,
  "",
  "## By regional office (관할 지방병무청)",
  "",
  header,
  ...groupBy(rows, "gtcdNm").map(([name, list]) => tableRow(name, list)),
  "",
  "## Largest 대표기관 on the 병무청 공통 규정",
  "",
  "Research and user-report priority: the 대표기관 that cover the most 복무기관 and have no registry record.",
  "",
  "| 대표기관 | 관할청 | 복무기관 |",
  "| --- | --- | ---: |",
  ...uncoveredParents.map(
    ([name, list]) => `| ${name} | ${list[0].gtcdNm} | ${list.length} |`,
  ),
  "",
  "## 제주 (all 대표기관)",
  "",
  `${jeju.length} 복무기관 under ${jejuParents.length} 대표기관 in the 제주 office's list. ` +
    "The research column summarises what the 2026-10-23 제주 survey found for that body; details are in the 제주 section of `docs/INSTITUTION_RULES_COVERAGE.md`.",
  "",
  header,
  tableRow("**제주 전체**", jeju),
  "",
  "| 대표기관 | 분류 | 복무기관 | 판정 | 레지스트리 | 조사 결과 |",
  "| --- | --- | ---: | --- | --- | --- |",
  ...jejuParents.map(([name, list]) => {
    const c = count(list);
    const status = Object.entries(c)
      .filter(([, n]) => n)
      .map(([key, n]) => `${STATUS[key]} ${n}`)
      .join(", ");
    const ids = [...new Set(list.map((row) => row.registryId).filter(Boolean))];
    return `| ${name} | ${list[0].ssggdaeBr} | ${list.length} | ${status} | ${ids.map((id) => `\`${id}\``).join(" ")} | ${jejuResearch[name] ?? "미조사"} |`;
  }),
  "",
];
fs.writeFileSync(
  path.join(root, "docs/INSTITUTION_ROSTER_CENSUS.md"),
  lines.join("\n"),
);
const total = count(rows);
console.log(
  `census: ${rows.length} 복무기관, OWN ${total.OWN}, PARENT ${total.PARENT}, SCOPE ${total.SCOPE}, NONE ${total.NONE}`,
);
